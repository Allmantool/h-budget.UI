import { appendFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

const command = process.argv[2];

try {
	if (command === 'check-open-pr') checkOpenPr();
	else if (command === 'evaluate') evaluateUpdaterRun();
	else if (command === 'write-pr-body') writePullRequestBody();
	else throw new Error('usage: ci-state.mjs check-open-pr|evaluate|write-pr-body');
} catch (error) {
	const message = error instanceof Error ? error.message : String(error);
	if (command === 'evaluate' && process.env.GITHUB_STEP_SUMMARY) {
		appendFileSync(
			process.env.GITHUB_STEP_SUMMARY,
			`## Safe npm Dependency Update\n\n- Decision: \`failed\`\n- Failure: ${escapeMarkdown(message)}\n\n`
		);
	}
	console.error(message);
	process.exitCode = 1;
}

function checkOpenPr() {
	const mode = requiredMode();
	const botLogin = requiredOption('--bot-login');
	const pullRequests = readJsonFile(requiredOption('--input'));
	if (!Array.isArray(pullRequests)) throw new Error('GitHub PR query must return an array.');
	if (pullRequests.length > 1) throw new Error(`Multiple open automation PRs exist for ${mode}; refusing to mutate.`);

	const pullRequest = pullRequests[0];
	if (!pullRequest) {
		writeGithubOutput({ should_run: 'true', existing_pr: '' });
		return;
	}

	const marker = ownershipMarker(mode);
	if (pullRequest.author?.login !== botLogin || !String(pullRequest.body ?? '').includes(marker)) {
		throw new Error(
			`Open dependency PR #${pullRequest.number ?? '<unknown>'} is not owned by this automation; refusing to overwrite it.`
		);
	}

	writeGithubOutput({
		should_run: 'false',
		existing_pr: String(pullRequest.url ?? pullRequest.number ?? ''),
	});
}

function evaluateUpdaterRun() {
	const exitCode = Number(requiredOption('--exit-code'));
	if (!Number.isInteger(exitCode)) throw new Error('Updater exit code must be an integer.');
	const state = readUpdaterState(exitCode);
	const status = String(state.status ?? 'missing');
	let decision;

	if (status === 'no-updates') {
		if (exitCode !== 0) throw new Error(`Updater reported no updates but exited with ${exitCode}.`);
		assertNoDependencyDiff();
		decision = 'no-updates';
	} else if (status === 'completed' || status === 'completed-with-rejections') {
		if (exitCode !== 0) throw new Error(`Updater reported ${status} but exited with ${exitCode}.`);
		if (Array.isArray(state.accepted) && state.accepted.length) {
			assertAcceptedDiff(state);
			decision = 'create-pr';
		} else {
			assertNoDependencyDiff();
			decision = 'no-accepted-updates';
		}
	} else if (status === 'lock-contention') {
		if (exitCode !== 3) throw new Error(`Lock contention must exit with code 3, received ${exitCode}.`);
		assertNoDependencyDiff();
		decision = 'lock-contention';
	} else {
		throw new Error(`Updater did not complete safely (status: ${status}, exit code: ${exitCode}).`);
	}

	appendSummary(state, decision);
	writeGithubOutput({ decision, updater_status: status });
}

function writePullRequestBody() {
	const mode = requiredMode();
	const state = readUpdaterState();
	if (
		!['completed', 'completed-with-rejections'].includes(state.status) ||
		!Array.isArray(state.accepted) ||
		!state.accepted.length
	) {
		throw new Error('A PR body can only be created for a completed updater run with accepted updates.');
	}

	const accepted = state.accepted.map(formatAccepted).join('\n');
	const rejected = formatEntries(state.rejected, formatRejected);
	const skipped = formatEntries(state.skipped, formatSkipped);
	const deferred = formatEntries(
		(state.skipped ?? []).filter(entry =>
			/specialized migration|framework|manual/i.test(String(entry.reason ?? ''))
		),
		formatSkipped
	);
	const workflowUrl = process.env.GITHUB_WORKFLOW_URL ?? 'Unavailable outside GitHub Actions';
	const warnings = formatEntries(state.warnings, warning => `- ${escapeMarkdown(warning)}`);
	const body = `${ownershipMarker(mode)}
## Safe npm dependency update

This PR was generated by the verified h-budget safe dependency updater.

- Mode: \`${mode}\`
- Updater status: \`${escapeMarkdown(state.status)}\`
- Updater run ID: \`${escapeMarkdown(state.runId ?? 'unknown')}\`
- Workflow run: ${workflowUrl}

### Accepted packages

${accepted}

### Rejected packages

${rejected}

### Skipped packages

${skipped}

### Deferred framework or migration-required packages

${deferred}

### Validation performed

- Strict \`npm ci\` and \`npm ls --depth=0\`
- Dependency guard and framework verification
- Lint, CI tests, and production build
- Exact lockfile verification and dependency-only diff validation

### Known warnings

${warnings}
`;
	writeFileSync(requiredOption('--output'), body);
}

function assertAcceptedDiff(state) {
	const accepted = Array.isArray(state.accepted) ? state.accepted : [];
	if (!accepted.length) throw new Error('Updater reported completion without accepted updates.');

	git(['diff', '--check']);
	const changedFiles = git(['diff', '--name-only']).split(/\r?\n/).filter(Boolean).sort();
	const expectedFiles = ['package-lock.json', 'package.json'];
	if (
		changedFiles.length !== expectedFiles.length ||
		changedFiles.some((file, index) => file !== expectedFiles[index])
	) {
		throw new Error(`Unexpected dependency-update diff: ${changedFiles.join(', ') || '<empty>'}.`);
	}

	const manifest = readJsonFile('package.json');
	const lockfile = readJsonFile('package-lock.json');
	for (const candidate of accepted) {
		if (!candidate?.name || !candidate?.section || !candidate?.to || !candidate?.toVersion) {
			throw new Error('Updater state contains an incomplete accepted candidate.');
		}
		if (manifest[candidate.section]?.[candidate.name] !== candidate.to) {
			throw new Error(`${candidate.name} does not match its accepted manifest target.`);
		}
		if (lockfile.packages?.[`node_modules/${candidate.name}`]?.version !== candidate.toVersion) {
			throw new Error(`${candidate.name} does not match its accepted lockfile target.`);
		}
	}
}

function assertNoDependencyDiff() {
	git(['diff', '--check']);
	const changedFiles = git(['diff', '--name-only']).split(/\r?\n/).filter(Boolean);
	if (changedFiles.length) throw new Error(`Updater reported no mutation but changed: ${changedFiles.join(', ')}.`);
}

function appendSummary(state, decision) {
	const summaryFile = process.env.GITHUB_STEP_SUMMARY;
	if (!summaryFile) return;
	const accepted = Array.isArray(state.accepted) ? state.accepted : [];
	const rejected = Array.isArray(state.rejected) ? state.rejected : [];
	const skipped = Array.isArray(state.skipped) ? state.skipped : [];
	appendFileSync(
		summaryFile,
		`## Safe npm Dependency Update\n\n- Mode: \`${escapeMarkdown(state.mode ?? 'unknown')}\`\n- Updater status: \`${escapeMarkdown(state.status ?? 'missing')}\`\n- Decision: \`${decision}\`\n- Accepted: ${accepted.length}\n- Rejected: ${rejected.length}\n- Skipped: ${skipped.length}\n\n`
	);
}

function formatAccepted(candidate) {
	return `- \`${escapeMarkdown(candidate.name)}\`: \`${escapeMarkdown(candidate.from)}\` → \`${escapeMarkdown(candidate.to)}\` (lock \`${escapeMarkdown(candidate.fromVersion)}\` → \`${escapeMarkdown(candidate.toVersion)}\`)`;
}

function formatRejected(candidate) {
	return `- \`${escapeMarkdown(candidate.name)}\`: ${escapeMarkdown(candidate.reason ?? 'rejected during validation')}`;
}

function formatSkipped(candidate) {
	return `- \`${escapeMarkdown(candidate.name)}\`: ${escapeMarkdown(candidate.reason ?? 'skipped by policy')}`;
}

function formatEntries(entries, formatter) {
	return Array.isArray(entries) && entries.length ? entries.map(formatter).join('\n') : '- None';
}

function readUpdaterState(exitCode) {
	const statePath = requiredOption('--state');
	const state = existsSync(statePath) ? readJsonFile(statePath) : readLockContentionState(statePath, exitCode);
	if (!state || typeof state !== 'object' || state.schemaVersion !== 1) {
		throw new Error('Updater state schema is unsupported or invalid.');
	}
	return state;
}

function readLockContentionState(statePath, exitCode) {
	if (exitCode !== 3) throw new Error(`Updater state file does not exist: ${statePath}`);
	const stateDirectory = join(statePath, '..');
	const contentionFile = readdirSync(stateDirectory)
		.filter(file => /^lock-contention-.+\.json$/.test(file))
		.sort()
		.at(-1);
	if (!contentionFile) throw new Error('Updater exited with lock contention but did not write contention evidence.');
	return readJsonFile(join(stateDirectory, contentionFile));
}

function writeGithubOutput(values) {
	const outputFile = requiredOption('--output');
	const content = Object.entries(values)
		.map(([key, value]) => `${key}=${String(value).replace(/[\r\n]/g, '')}`)
		.join('\n');
	appendFileSync(outputFile, `${content}\n`);
}

function git(args) {
	const result = spawnSync('git', args, { cwd: process.cwd(), encoding: 'utf8' });
	if (result.status !== 0)
		throw new Error(`git ${args.join(' ')} failed: ${result.stderr?.trim() || 'unknown error'}`);
	return result.stdout ?? '';
}

function readJsonFile(file) {
	return JSON.parse(readFileSync(file, 'utf8'));
}

function requiredMode() {
	const mode = requiredOption('--mode');
	if (!['patch', 'minor', 'major'].includes(mode)) throw new Error(`Invalid dependency update mode: ${mode}`);
	return mode;
}

function requiredOption(name) {
	const index = process.argv.indexOf(name);
	const value = index >= 0 ? process.argv[index + 1] : undefined;
	if (!value || value.startsWith('--')) throw new Error(`Missing required option ${name}.`);
	return value;
}

function ownershipMarker(mode) {
	return `<!-- safe-dependency-updater: mode=${mode}; schema=1 -->`;
}

function escapeMarkdown(value) {
	return String(value ?? 'unknown').replace(/[\r\n`|]/g, ' ');
}
